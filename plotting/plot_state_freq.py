import numpy as np
import pandas as pd
import matplotlib.pyplot as plt
import matplotlib
matplotlib.use('Agg')  # Use non-interactive backend for HPC/headless environments
import argparse

"""
This script plots the contact state frequencies for all sequences on a stacked bar chart.
"""

def read_data_file(sequence): 
    """
    Reads the odds ratios from a file generated by calc_odds_ratios.py

    Arguments
        sequence : str
            The sequence to read the odds ratios for

    Returns
        OR_data : pandas.DataFrame
            A DataFrame containing the odds ratios for the given sequence
    """

    OR_data = pd.read_csv(f"{input_path}/{sequence}_wrapped_centered_PIF_equil_del_odds_ratios_{association}.txt", sep=r'\s+', header=None, names=['blob_association', 'state_a', 'state_b', 'state_c', 'state_d', 'OR'])
    
    return OR_data

def plot_state_freq():
    """
    Plots the state frequencies for all sequences and blob pairs for a given association.

    Arguments
        None

    Returns
        None
    """

    state_a, state_b, state_c, state_d = [], [], [], []
    state_a_sem, state_b_sem, state_c_sem, state_d_sem = [], [], [], []

    labels = []

    # Read frequencies for each variant
    for sequence in sequences:
        data_df = read_data_file(sequence)
        row = data_df.iloc[0]

        counts = np.array([
            row["state_a"],
            row["state_c"], #NOTICE THE SWITCH FROM STATE B TO C. SWITCHING THE ORDER FOR ANNOTATION PURPOSES
            row["state_b"], #NOTICE THE SWITCH FROM STATE C TO B. SWITCHING THE ORDER FOR ANNOTATION PURPOSES
            row["state_d"]
        ], dtype=float)

        N = counts.sum()

        # Convert to percentages
        freqs = counts / N * 100

        # Binomial SEM (%)
        sems = np.sqrt((counts / N) * (1 - counts / N) / N) * 100

        # Store frequencies in list
        state_a.append(freqs[0])
        state_b.append(freqs[1])
        state_c.append(freqs[2])
        state_d.append(freqs[3])

        # Store SEMs in list
        state_a_sem.append(sems[0])
        state_b_sem.append(sems[1])
        state_c_sem.append(sems[2])
        state_d_sem.append(sems[3])

        labels.append(sequence)

    # Plot
    fig, ax = plt.subplots(figsize=(8, 6))

    bottom = np.zeros(len(labels))

    state_data = [state_a, state_b, state_c, state_d]
    state_sems = [state_a_sem, state_b_sem, state_c_sem, state_d_sem]
    state_names = ["A", "B", "C", "D"]

    x = np.arange(len(labels))

    alphas = np.linspace(1.0, 0.1, len(state_data))

    for i, (values, errors, state) in enumerate(zip(state_data, state_sems, state_names)):
        ax.bar(
            x,
            values,
            bottom=bottom,
            color=color,   
            alpha=alphas[i],
            label=state
        )

        ax.errorbar(
            x=x,
            y=bottom + np.array(values),
            yerr=errors,
            fmt="none",
            ecolor="black",
            capsize=5,
            elinewidth=1
        )

        bottom += np.array(values)

    ax.set_xticks(x)
    ax.set_xticklabels(labels, fontsize=18)
    ax.set_ylabel("Frequency (%)", fontsize=20)
    ax.tick_params(axis='y', labelsize=18)

    plt.tight_layout()
    plt.savefig(f"{output_path}/{output_file_name}.pdf", bbox_inches="tight")
    plt.close()

if __name__ == "__main__":

    parser = argparse.ArgumentParser(description="Plot the frequencies of contact states in the entire ensemble.")

    parser.add_argument("--association", required=True, help="Odds ratio association.") 
    parser.add_argument("--bar_plot_color", required=True, help="Color of the bar plot.")
    parser.add_argument("--input_path", required=True, help="Path to the input data.") 
    parser.add_argument("--output_path", required=True, help="Path to the output data.")
    parser.add_argument("--sequences", required=False, default="F66 M66 V66 L66 A66 Y66 I66", help="Sequence names.")

    args = parser.parse_args()

    association = args.association
    color = args.bar_plot_color
    input_path = args.input_path
    output_path = args.output_path
    sequences = args.sequences.split()
    
    output_file_name = f"state_freq_{association}"

    plot_state_freq()
