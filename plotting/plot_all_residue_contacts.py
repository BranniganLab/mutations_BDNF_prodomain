def plot_contact_frequency_heatmap(ax, sequence, fig):
    """
    Generates a contact-frequency heatmap for one sequence.

    Arguments:
        ax : matplotlib.axes.Axes
            The axes on which to plot the heatmap.
        sequence : str
            The sequence being plotted.
        fig : matplotlib.figure.Figure
            The figure containing the axes.

    Returns:
        imgp : matplotlib.image.AxesImage
            The plotted image.
    """
    contact_freq_data = read_contact_file_generated_by_tcl(sequence)
    contact_freq_matrix = create_heatmap_matrix(contact_freq_data)

    return plot_heatmap(ax, sequence, fig, contact_freq_matrix, 'Purples', 0, 12, f"{sequence[0]}66", 30)

def plot_difference_heatmap(ax, sequence, reference_sequence, fig):
    """
    Generates a contact-frequency difference heatmap for one sequence.

    Arguments:
        ax : matplotlib.axes.Axes
            The axes on which to plot the heatmap.
        sequence : str
            The sequence being compared.
        reference_sequence : str
            The sequence used as the reference.
        fig : matplotlib.figure.Figure
            The figure containing the axes.

    Returns:
        imgp : matplotlib.image.AxesImage
            The plotted image.
    """
    contact_frequency_difference = calculate_contact_frequency_difference(sequence, reference_sequence)

    return plot_heatmap(ax, sequence, fig, contact_frequency_difference, 'PRGn', -12, 12, f"{sequence[0]}66 - {reference_sequence[0]}66", 20)

def plot_combined():
    """
    Generates the regular 2-by-4 contact-frequency heatmap figure.
    
    Arguments:
        None
    
    Returns:
        None
    """
    fig, axes = plt.subplots(2, 4, figsize=(20, 10))

    # TOP ROW
    plot_contact_frequency_heatmap(axes[0, 0], "F", fig)
    plot_contact_frequency_heatmap(axes[0, 1], "M", fig)
    plot_contact_frequency_heatmap(axes[0, 2], "V", fig)
    plot_contact_frequency_heatmap(axes[0, 3], "L", fig)

    # BOTTOM ROW
    plot_contact_frequency_heatmap(axes[1, 0], "A", fig)
    plot_contact_frequency_heatmap(axes[1, 1], "Y", fig)
    plot_contact_frequency_heatmap(axes[1, 2], "I", fig)
    axes[1, 3].axis('off')

    plt.savefig(f"{output_path}/{output_filename}", bbox_inches='tight')
    plt.close()

