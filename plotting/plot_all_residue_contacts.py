def read_contact_file_generated_by_tcl(sequence):
    """
    Reads the input file and parses the residue pairs with their values.
    """

    contact_filename = f'{res_type}_contactfreqs_6A_{sequence}_{state}.txt'
    contact_freq_data = pd.read_csv(f'{input_path}/{contact_filename}', sep=r'\s+', header=None, names=["Row", "Column", "Value"])

    return contact_freq_data

def create_heatmap_matrix(contact_freq_data):
    """
    Converts the residue pair data into a matrix for heatmap plotting.
    """
    # Create a unique set (no duplicates of all data) with the row and columns and sort them to determine the matrix size (sequence length)
    all_labels = sorted(set(contact_freq_data["Row"]).union(set(contact_freq_data["Column"])))
    label_to_index = {label: i for i, label in enumerate(all_labels)}
    matrix_size = len(all_labels)
    contact_freq_matrix = np.zeros((matrix_size, matrix_size))
    
    for _, row in contact_freq_data.iterrows():
        j = label_to_index[row["Row"]]
        i = label_to_index[row["Column"]]
        contact_freq_matrix[i, j] = row["Value"]
        contact_freq_matrix[j, i] = row["Value"]

    return contact_freq_matrix

