def scale_contingency_table(a, b, c, d):
    """
    Scales a 2x2 contingency table of counts (a, b, c, d) to have n_independent_samples observations

    Arguments
        OR : float
            the odds ratio
        a : int
            number of positive counts in the first group
        b : int
            number of negative counts in the first group
        c : int
            number of positive counts in the second group
        d : int
            number of negative counts in the second group

    Returns
        scaled_int : numpy.ndarray
            the scaled contingency table
    """

    counts = np.array([a, b, c, d], dtype=float)

    n_frames = counts.sum()

    scaled = counts * (n_independent_samples / n_frames)

    # Start with integer counts below the desired values
    scaled_int = np.floor(scaled).astype(int)

    # Number of observations still needed to reach n_independent_samples
    remainder = n_independent_samples - scaled_int.sum()

    # Give remaining observations to cells with largest fractional parts
    fractional = scaled - scaled_int
    order = np.argsort(fractional)[::-1]

    for i in order[:remainder]:
        scaled_int[i] += 1

    return scaled_int

def compute_fisher_exact(a, b, c, d):
    """
    Computes the Fisher's exact test for a 2x2 contingency table of counts (a, b, c, d)

    Arguments
        a : int
            number of positive counts in the first group
        b : int
            number of negative counts in the first group
        c : int
            number of positive counts in the second group
        d : int
            number of negative counts in the second group

    Returns
        odds_ratio : float
            the odds ratio
        p_value : float
            the p-value of the Fisher's exact test
    """

    # Corrected contingency table
    a_corrected, b_corrected, c_corrected, d_corrected = scale_contingency_table(a, b, c, d)

    # Fisher test using corrected values
    odds_ratio, p_value = stats.fisher_exact([[a_corrected, b_corrected], [c_corrected, d_corrected]])

    return odds_ratio, p_value

def association_to_blob_names(association):
    """
    Converts an association such as '8_12_to_12_2' to blob contact names such as 'v-m' and 'm-n'.

    Arguments
        association : str
            an association such as '8_12_to_12_2'

    Returns
        name_A : str
            a blob contact name such as 'v-m'
        name_B : str
            a blob contact name such as 'm-n'   
    """

    contact_A, contact_B = association.split("_to_")

    blob1_A, blob2_A = map(int, contact_A.split("_"))
    blob1_B, blob2_B = map(int, contact_B.split("_"))

    name_A = f"{blob_id_to_blob_name[blob1_A]}-{blob_id_to_blob_name[blob2_A]}"
    name_B = f"{blob_id_to_blob_name[blob1_B]}-{blob_id_to_blob_name[blob2_B]}"

    return name_A, name_B

def plot_OR():
    """
    Plots the odds ratios for all sequences of two blob pairs for a given association.

    Arguments
        None

    Returns
        None
    """

    odds_ratios = []
    ci_lowers = []
    ci_uppers = []
    p_values = []

    for sequence in sequences:
        data_df = read_OR_file(sequence)
        state_a = data_df.iloc[0, 1]
        state_b = data_df.iloc[0, 2]
        state_c = data_df.iloc[0, 3]
        state_d = data_df.iloc[0, 4]

        # Use Fisher exact test to determine whether the odds ratios are significant from 1
        fisher_OR, p = compute_fisher_exact(state_a, state_b, state_c, state_d)

        # Use Wald test for calculating the confidence intervals and plotting the error bars
        ci_lower, ci_upper = calc_confidence_intervals(fisher_OR, state_a, state_b, state_c, state_d)

        odds_ratios.append(fisher_OR)
        ci_lowers.append(ci_lower)
        ci_uppers.append(ci_upper)
        p_values.append(p)

    odds_ratios = np.array(odds_ratios)
    ci_lowers = np.array(ci_lowers)
    ci_uppers = np.array(ci_uppers)

    yerr = [odds_ratios - ci_lowers, ci_uppers - odds_ratios]

    fig, ax = plt.subplots(figsize=(8, 6))

    ax.bar(sequences, odds_ratios, yerr=yerr, capsize=5, color='gray')

    plt.axhline(1.0, linestyle="--", color='black')

    for i, p in enumerate(p_values):

        if p < 0.001:
            star = "***"
        elif p < 0.01:
            star = "**"
        elif p < 0.05:
            star = "*"
        else:
            star = ""

        if star:
            plt.text(i,ci_uppers[i] + 0.0, star, ha="center", fontsize=16)

