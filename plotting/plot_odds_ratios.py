def calc_confidence_intervals(OR, a, b, c, d):
    """
    Computes the standard error of the log odds ratio and calculates the confidence interval for a 2x2 contingency table of counts (a, b, c, d)

    Arguments
        OR : float
            the odds ratio
        a : int
            number of positive counts in the first group
        b : int
            number of negative counts in the first group
        c : int
            number of positive counts in the second group
        d : int
            number of negative counts in the second group

    Returns
        ci_lower : float
            the lower bound of the 95% confidence interval
        ci_upper : float
            the upper bound of the 95% confidence interval
    """

    log_OR = np.log(OR)
    
    se_log_OR = np.sqrt(1/a + 1/b + 1/c + 1/d)

