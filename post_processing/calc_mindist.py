import subprocess
import pandas as pd
import argparse

def mindist():
    """
    Calculates minimum distance of two atoms in the trajectory. This function is useful when determining if the protein is interacting with itself in the periodic image.

    Arguments:
        None

    Returns:
        None
    """

    subprocess.call(f"echo 1 > pro ; gmx mindist -f {input_traj_path}/{seq}_wrapped_centered.xtc -s {raw_traj_path}/{seq}/{seq}.tpr -xvg none -od {seq}_mindist.xvg -pi < pro", shell=True, cwd=output_data_path)

def write_periodic_image_frames_to_list():
    """
    This function reads a mindist.xvg generated by the GROMACS mindist command. If the mindist value is less than 2nm, it appends the associated time frame to a list.
    It is important to delete the frames in which a protein interacts with its periodic image. The -pi flag will plot the minimum distance of the protein to its
    periodic image. The time frame list will then be used to delete the frames out of the trajectory. 

    Arguments:
        None

    Returns:
        list_of_time_frames_to_delete : list
            List of time frames that contain periodic images which should be deleted.
    """

    mindist_file = pd.read_csv(f"{output_data_path}/{seq}_mindist.xvg", sep="\t\t|\t+|\s+", index_col=False, names=['time_frame', 'mindist'], engine='python', usecols=[0,2]) #load 0th and 2nd column of mindist.xvg
    list_of_time_frames_to_delete =[]

    for mindist_value, time_frame in zip(mindist_file['mindist'], mindist_file['time_frame']):
        if mindist_value < max_value:
            frame_scaled = time_frame
            frame = int(frame_scaled / 100) # Convert the frame to time 
            if frame > 0:
                list_of_time_frames_to_delete.append(frame)

    return list_of_time_frames_to_delete

def write_to_text_file(list_of_time_frames_to_delete):
    """
        Writes list to text file.
    """
    file = open(f'{output_data_path}/{seq}_mindist_frames_to_delete.txt', 'w')
    for item in list_of_time_frames_to_delete:
        file.write(str(item) + "\n")
    file.close()

if __name__=="__main__":

    parser = argparse.ArgumentParser(description="Calculates the minimum distance between two atoms in the trajectory and determines if the protein is interacting with itself in the periodic image by a cutoff distance.")

    parser.add_argument("--raw_traj_path", required=True, help="Path to the input data.") 
    parser.add_argument("--input_traj_path", required=True, help="Path to the input data.") 
    parser.add_argument("--output_data_path", required=True, help="Path to the output data.")
    parser.add_argument("--sequences", required=False, default="F66 M66 V66 L66 A66 Y66 I66", help="Sequence names.")
    parser.add_argument("--max_distance", required=False, default=2, help="Maximum distance between two atoms in nm.")

    args = parser.parse_args()

    raw_traj_path = args.raw_traj_path
    input_traj_path = args.input_traj_path
    output_data_path = args.output_data_path
    sequences = args.sequences.split()
    max_value = float(args.max_distance)
        
    for seq in sequences:
        mindist()
        list_of_time_frames_to_delete = write_periodic_image_frames_to_list()
        write_to_text_file(list_of_time_frames_to_delete)